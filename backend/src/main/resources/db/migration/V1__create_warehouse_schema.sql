CREATE TABLE products (
  id UUID PRIMARY KEY,
  sku VARCHAR(48) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  category VARCHAR(80) NOT NULL
);

CREATE TABLE inventory_containers (
  shelf_id VARCHAR(32) PRIMARY KEY,
  column_code VARCHAR(12) NOT NULL,
  level INTEGER NOT NULL CHECK (level BETWEEN 1 AND 3),
  product_id UUID NOT NULL UNIQUE REFERENCES products(id),
  current_stock INTEGER NOT NULL DEFAULT 0 CHECK (current_stock >= 0),
  max_capacity INTEGER NOT NULL CHECK (max_capacity > 0),
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT inventory_capacity_check CHECK (current_stock <= max_capacity)
);

CREATE TABLE stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  container_id VARCHAR(32) NOT NULL REFERENCES inventory_containers(shelf_id),
  movement_type VARCHAR(8) NOT NULL CHECK (movement_type IN ('ADD', 'REMOVE')),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  resulting_stock INTEGER NOT NULL CHECK (resulting_stock >= 0),
  note VARCHAR(120),
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX stock_movements_container_time_idx ON stock_movements(container_id, occurred_at DESC, id DESC);
